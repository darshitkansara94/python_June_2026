# Inheritance :
#     Inheritance is a accessing method or property of the parent class through
#         child class.
#     Here parent class is also consider as a base class.
#     And child class is consider as a derived class.
#     This concept follows reusability of code.

#     Syntax :
#         class parent_class():
#             property
#             methods

#         class child_class(parent_class):
#             property
#             method


# Encapsulation :
#     Encapsulation is a implemetation where we can not access / modify the 
#         actual logic or value.
#     We can only use that method from the class by creating oject.
#     Ex :
#         Washing machine when we start machine we don't know the actual process that run
#             behind the start button.
#         but machine wash clothes, intake water etc.
#     likewise, we can not see actual implemetation but we can access the method of the 
#         class and we can use it.

# Public property :
#     Public property is something that can be access outside of the class.
#     And user can change a value of that property easily.

# Private Property :
#     Private property is not accessible outside of that class.
#     We can implement it inside the class only so user can not modify it's value 
#     if user want to then through the method user can change it's value.
#     If we can see '__'(double underscore) before variable name then it will
#         consider as a private property or variable.

#     Syntax :
#         __variable_name

# Get and Set :
#     Get is use to fetch value from a private property.
#     Set is use to assign a value to private property.



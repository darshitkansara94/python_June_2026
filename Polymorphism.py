# Polymorphism :
#     Polymorphism is one form is associated with many other forms.
#     In python, Polymorphism is one funtion or one class associate with other
#         function or class.
#     There are function type Polymorphism and class Polymorphism.
#     The basic comcept of Polymorphism is reusability of the code.

#     Example :

print("This is first print")
